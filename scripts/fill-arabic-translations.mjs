const locale = JSON.parse(fs.readFileSync(LOCALE_PATH, 'utf8'));

let filled = 0;
let notFound = 0;
for (const [key, value] of Object.entries(TRANSLATIONS)) {
	if (typeof locale[key] === 'string') {
		if (locale[key] === '') {
			locale[key] = value;
			filled++;
		}
	} else {
		notFound++;
	}
}

fs.writeFileSync(LOCALE_PATH, JSON.stringify(locale, null, '\t') + '\n', 'utf8');
console.log(`Filled ${filled} translations; ${notFound} keys not present in locale`);
